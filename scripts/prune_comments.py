"""Find comments that carry no information, and optionally remove them.

**This tool is deliberately conservative, and reports by default.** In this
codebase comments are load-bearing: they record *why* a decision was made,
which defect it prevents, and what a passing test does not establish. A
stripper tuned for aggression would delete the most valuable lines in the
repository, and nothing downstream would notice until someone reintroduced
a bug the comment existed to warn about.

So the rule is inverted from the usual one. Rather than guessing which
comments are useful, this only removes comments matching an explicit
denylist of patterns that are useless *by construction*:

    - Restating the code on the next line ("# increment i" above `i += 1`)
    - Section banners made of punctuation with no words
    - Commented-out code (dead code hiding as prose, §92)
    - Editor and agent leftovers ("# TODO: fix", "# FIXME later" with no
      detail, "# noqa" with no rule, autogenerated markers)
    - Empty comments

Anything else is left alone, including comments this script cannot classify.
A false negative wastes a line; a false positive destroys the reason a piece
of code exists.

Usage:

    python scripts/prune_comments.py                 # report, change nothing
    python scripts/prune_comments.py --diff          # show what would change
    python scripts/prune_comments.py --apply         # rewrite the files
    python scripts/prune_comments.py --path src/x.py # limit the scope

`--apply` refuses to run on a dirty working tree, so every removal is
reviewable as a single commit and revertible with `git checkout`.
"""

from __future__ import annotations

import argparse
import ast
import io
import re
import subprocess
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# Directories never touched: generated, vendored, or experimental material
# whose comments are part of what is being studied.
SKIP_DIRECTORIES = {
    ".git",
    ".venv",
    "venv",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
    ".hypothesis",
    "node_modules",
    "dist",
    "build",
    # Fixtures are copied into agent workspaces and edited by agents under
    # test. Rewriting their comments would alter the experiment.
    "fixtures",
    "data",
    "artifacts",
    "experiments",
}

# Comments that are useless by construction.
NOISE_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    # A bare "#" is only noise when it stands alone. Inside a comment block
    # it is a paragraph break, and removing it runs two separate arguments
    # together. The first version of this rule flagged 13 of them across
    # this codebase, every one a separator in a multi-paragraph rationale.
    ("empty", re.compile(r"^#\s*$")),
    # A banner of punctuation with no words: "# -----", "# =====", "# ###".
    ("banner", re.compile(r"^#\s*[-=*#~_/\\+.]{3,}\s*$")),
    # Bare markers with no detail. "# TODO: wire up the retry" is kept;
    # "# TODO" and "# FIXME later" carry nothing.
    ("bare_marker", re.compile(r"^#\s*(TODO|FIXME|XXX|HACK|NOTE)\s*[:.!]?\s*$", re.I)),
    (
        "vague_marker",
        re.compile(r"^#\s*(TODO|FIXME)\s*[:.]?\s*(fix|later|this|it|me)\s*[.!]?\s*$", re.I),
    ),
    # Autogenerated leftovers.
    # Anchored and terminated: "# Autogenerated leftovers." is a category
    # label in prose, not a generated-file marker. The unanchored version
    # flagged this very file's own comment.
    (
        "generated",
        re.compile(
            r"^#\s*(-\*-\s*coding[:=]|!?\s*autogenerated\s*$|generated by [\w.]+\s*$|DO NOT EDIT)",
            re.I,
        ),
    ),
    # Agent and editor debris.
    ("debris", re.compile(r"^#\s*(mutation|debug|test123|asdf|xxx+)\s*[.!]?\s*$", re.I)),
]

# Words that make a comment explanatory rather than restating. If any appear,
# the comment is kept even if it looks like a restatement — these signal a
# reason, a caveat, or a reference.
REASON_WORDS = re.compile(
    r"\b(because|so that|otherwise|rather than|instead|would|could|must|"
    r"never|always|deliberate|deliberately|intentional|why|reason|avoid|"
    r"prevent|ensure|note that|caveat|limitation|spec|§|see |RFC|bug|"
    r"defect|regression|fails|failure|silently|hidden|confound)\b",
    re.I,
)


@dataclass(frozen=True)
class Finding:
    path: Path
    line: int
    text: str
    kind: str

    def render(self) -> str:
        # Relative when inside the repo, absolute otherwise. `--path` accepts
        # any location, and relative_to raises rather than falling back —
        # which crashed the reporter the first time it was pointed at a file
        # outside the tree.
        try:
            shown: Path | str = self.path.relative_to(REPO)
        except ValueError:
            shown = self.path
        return f"{shown}:{self.line}  [{self.kind}]  {self.text.strip()}"


def is_commented_out_code(text: str) -> bool:
    """Whether a comment is really a line of Python that was commented out.

    Parsed rather than pattern-matched: `# self.x = 1` is code, while
    `# x is the offset` merely mentions a name. Trying to tell those apart
    with a regex produces exactly the false positives this tool must not
    make.
    """
    body = text.lstrip("#").strip()
    if not body or len(body) < 4:
        return False
    # Prose that happens to parse — a bare name, a string, a number — is not
    # commented-out code in any meaningful sense.
    try:
        tree = ast.parse(body)
    except SyntaxError:
        return False
    if not tree.body:
        return False
    node = tree.body[0]
    if isinstance(node, ast.Expr) and isinstance(
        node.value, (ast.Name, ast.Constant, ast.Attribute)
    ):
        return False
    return isinstance(
        node,
        (
            ast.Assign,
            ast.AugAssign,
            ast.AnnAssign,
            ast.Return,
            ast.If,
            ast.For,
            ast.While,
            ast.With,
            ast.FunctionDef,
            ast.ClassDef,
            ast.Import,
            ast.ImportFrom,
            ast.Raise,
            ast.Assert,
            ast.Delete,
        ),
    ) or (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call))


def restates_next_line(comment: str, following: str) -> bool:
    """Whether a comment just names what the next line plainly does.

    Requires a strong overlap of identifiers and no explanatory language.
    A comment that gives a reason is never a restatement, however much
    vocabulary it shares with the code.
    """
    if REASON_WORDS.search(comment):
        return False
    # A pointer to an external authority — a spec section, an issue, an RFC —
    # is the most valuable kind of short comment, and the least like a
    # restatement. "# §11: base/run_id/agent_id" shares every word with the
    # line below it and is still the reason that line is correct.
    if re.search(r"(§|#\d+|RFC\s*\d|CVE-|https?://)", comment):
        return False
    body = comment.lstrip("#").strip().lower()
    if not body or len(body.split()) > 8:
        return False
    words = {w for w in re.findall(r"[a-z_]{3,}", body)}
    code_words = {w for w in re.findall(r"[a-z_]{3,}", following.lower())}
    if not words:
        return False
    overlap = words & code_words
    # Every meaningful word already appears in the code below it.
    return len(overlap) == len(words) and len(words) >= 2


def scan(path: Path) -> list[Finding]:
    """Find noise comments in one file."""
    try:
        source = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return []
    lines = source.splitlines()
    findings: list[Finding] = []

    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        # An unparseable file is left entirely alone rather than
        # line-scanned, which would misread comments inside strings.
        return []

    for token in tokens:
        if token.type != tokenize.COMMENT:
            continue
        text = token.string
        row = token.start[0]
        # Only whole-line comments are considered. A trailing comment sits
        # beside code it is explaining, which is the useful case.
        if lines[row - 1].strip() != text.strip():
            continue

        kind = None
        for name, pattern in NOISE_PATTERNS:
            if pattern.match(text.strip()):
                kind = name
                break

        # A bare "#" adjacent to another comment line is a paragraph break
        # inside a block, not a stray empty comment. Checked here rather
        # than in the pattern because it needs the neighbouring lines.
        if kind == "empty":
            above = lines[row - 2].strip() if row >= 2 else ""
            below = lines[row].strip() if row < len(lines) else ""
            if above.startswith("#") or below.startswith("#"):
                kind = None
        if kind is None and is_commented_out_code(text):
            kind = "commented_out_code"
        if kind is None and row < len(lines):
            following = lines[row].strip()
            if following and not following.startswith("#") and restates_next_line(text, following):
                kind = "restates_code"

        if kind:
            findings.append(Finding(path=path, line=row, text=text, kind=kind))

    return findings


def python_files(root: Path) -> list[Path]:
    found = []
    for path in root.rglob("*.py"):
        if any(part in SKIP_DIRECTORIES for part in path.parts):
            continue
        found.append(path)
    return sorted(found)


def apply_removals(findings: list[Finding]) -> int:
    """Delete the flagged lines. Returns how many were removed."""
    by_file: dict[Path, set[int]] = {}
    for finding in findings:
        by_file.setdefault(finding.path, set()).add(finding.line)

    removed = 0
    for path, rows in by_file.items():
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        kept = [line for i, line in enumerate(lines, start=1) if i not in rows]
        path.write_text("".join(kept), encoding="utf-8")
        removed += len(rows)
    return removed


def working_tree_is_clean() -> bool:
    result = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.returncode == 0 and not result.stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--apply", action="store_true", help="rewrite files")
    parser.add_argument("--diff", action="store_true", help="show surrounding context")
    parser.add_argument("--path", type=Path, help="limit to one file or directory")
    arguments = parser.parse_args()

    root = arguments.path if arguments.path else REPO
    targets = [root] if root.is_file() else python_files(root)

    findings: list[Finding] = []
    for path in targets:
        findings.extend(scan(path))

    if not findings:
        print(f"No noise comments found across {len(targets)} file(s).")
        return 0

    by_kind: dict[str, int] = {}
    for finding in findings:
        by_kind[finding.kind] = by_kind.get(finding.kind, 0) + 1

    for finding in findings:
        print(finding.render())
        if arguments.diff:
            lines = finding.path.read_text(encoding="utf-8").splitlines()
            start = max(finding.line - 3, 0)
            for offset, line in enumerate(lines[start : finding.line + 2], start=start + 1):
                marker = "  -" if offset == finding.line else "   "
                print(f"    {marker} {offset:>5} {line}")
            print()

    print(f"\n{len(findings)} finding(s) across {len({f.path for f in findings})} file(s):")
    for kind, count in sorted(by_kind.items()):
        print(f"  {count:>4}  {kind}")

    if not arguments.apply:
        print("\nReporting only. Re-run with --apply to remove them.")
        return 0

    if not working_tree_is_clean():
        print(
            "\nRefusing to rewrite files: the working tree has uncommitted "
            "changes.\nCommit or stash first, so every removal is reviewable "
            "as one commit and revertible with git checkout.",
            file=sys.stderr,
        )
        return 1

    removed = apply_removals(findings)
    print(f"\nRemoved {removed} line(s). Review with `git diff` before committing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
