"""Unit tests for the operational run index (spec §42, §63, §80).

The index is what makes resume possible and duplicate execution
impossible. Both properties fail silently if they fail at all — a resumed
collection that re-ran finished work would simply produce more data — so
the tests here try to break them rather than demonstrate them.
"""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import pytest

from causalmesh.experiments import plan_experiment, profile
from causalmesh.scheduler import InvalidTransitionError, RunState
from causalmesh.storage import RunIndex

pytestmark = pytest.mark.unit

SEED = b"causalmesh-run-index-unit-seed01"


@pytest.fixture
def plan():
    return plan_experiment(
        experiment_id="exp",
        profile=profile("pilot"),
        task_ids=["t1"],
        master_seed=SEED,
    )


@pytest.fixture
def index(tmp_path: Path):
    with RunIndex(tmp_path / "index.db") as opened:
        yield opened


class TestRegistration:
    def test_registering_a_plan_inserts_every_run(self, index: RunIndex, plan) -> None:
        assert index.register_plan(plan, now_us=1) == len(plan)
        assert len(index.runs("exp")) == len(plan)

    def test_every_run_starts_planned(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        assert index.counts("exp")[RunState.PLANNED] == len(plan)

    def test_registration_is_idempotent(self, index: RunIndex, plan) -> None:
        """§42. Re-planning before a resume must not reset progress."""
        index.register_plan(plan, now_us=1)
        assert index.register_plan(plan, now_us=2) == 0
        assert len(index.runs("exp")) == len(plan)

    def test_reregistering_does_not_reset_a_finished_run(
        self, index: RunIndex, plan
    ) -> None:
        index.register_plan(plan, now_us=1)
        claimed = index.claim_next("exp", now_us=2)
        index.finish(claimed.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)

        index.register_plan(plan, now_us=4)

        assert index.get(claimed.run_id).state == RunState.COMPLETED
        assert index.get(claimed.run_id).succeeded is True

    def test_a_changed_plan_under_the_same_id_is_refused(
        self, index: RunIndex, plan
    ) -> None:
        """Resuming under a changed design would pool two experiments.

        The runs would carry the same experiment_id and be analysed
        together despite having been generated by different designs.
        """
        index.register_plan(plan, now_us=1)
        different = plan_experiment(
            experiment_id="exp",
            profile=profile("small"),  # different repetition count
            task_ids=["t1"],
            master_seed=SEED,
        )
        with pytest.raises(ValueError, match="different plan"):
            index.register_plan(different, now_us=2)

    def test_the_plan_hash_is_stored(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        assert index.plan_hash("exp") == plan.content_hash()

    def test_an_unknown_experiment_has_no_plan_hash(self, index: RunIndex) -> None:
        assert index.plan_hash("nope") is None


class TestClaiming:
    def test_claiming_follows_the_randomized_order(self, index: RunIndex, plan) -> None:
        """§41: taking runs by task or by arm would restore blocking."""
        index.register_plan(plan, now_us=1)
        taken = []
        while (record := index.claim_next("exp", now_us=2)) is not None:
            taken.append(record.run_id)
            index.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)
        assert taken == [run.run_id for run in plan.runs]

    def test_claiming_marks_the_run_running(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=5)
        assert record.state == RunState.RUNNING
        assert record.started_at_us == 5
        assert record.attempts == 1

    def test_claiming_returns_none_when_nothing_is_runnable(
        self, index: RunIndex, plan
    ) -> None:
        index.register_plan(plan, now_us=1)
        while (record := index.claim_next("exp", now_us=2)) is not None:
            index.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)
        assert index.claim_next("exp", now_us=4) is None

    def test_a_running_run_is_not_claimed_again(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        first = index.claim_next("exp", now_us=2)
        second = index.claim_next("exp", now_us=3)
        assert first.run_id != second.run_id

    def test_a_finished_run_is_never_reclaimed(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        index.finish(record.run_id, state=RunState.FAILED, now_us=3)
        for _ in range(len(plan)):
            nxt = index.claim_next("exp", now_us=4)
            if nxt is None:
                break
            assert nxt.run_id != record.run_id
            index.finish(nxt.run_id, state=RunState.COMPLETED, now_us=5, succeeded=True)

    def test_claiming_is_atomic_under_concurrency(self, tmp_path: Path, plan) -> None:
        """No run may be claimed twice, even by simultaneous workers.

        Real threads against a real file-backed database, so the
        BEGIN IMMEDIATE transaction is genuinely exercised. A select
        followed by a separate update would let two workers both read
        PLANNED and both execute the same run, silently duplicating a
        result.
        """
        with RunIndex(tmp_path / "index.db") as index:
            index.register_plan(plan, now_us=1)

            def take_all() -> list[str]:
                taken = []
                while (record := index.claim_next("exp", now_us=2)) is not None:
                    taken.append(record.run_id)
                return taken

            with ThreadPoolExecutor(max_workers=6) as pool:
                results = [f.result() for f in [pool.submit(take_all) for _ in range(6)]]

            claimed = [run_id for batch in results for run_id in batch]
            assert len(claimed) == len(set(claimed)), "a run was claimed twice"
            assert set(claimed) == {run.run_id for run in plan.runs}


class TestFinishing:
    def test_a_completed_run_records_its_evidence(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        finished = index.finish(
            record.run_id,
            state=RunState.COMPLETED,
            now_us=9,
            succeeded=True,
            task_hash="th",
            head_hash="hh",
            artifact_path="/somewhere/run.json",
        )
        assert finished.state == RunState.COMPLETED
        assert finished.succeeded is True
        assert finished.head_hash == "hh"
        assert finished.finished_at_us == 9

    def test_completed_and_succeeded_are_independent(
        self, index: RunIndex, plan
    ) -> None:
        """§81. A run whose task failed is a result, not a lost run.

        Conflating execution status with task outcome would drop failed
        tasks from the denominator and turn the primary outcome into a
        survivorship rate.
        """
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        finished = index.finish(
            record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=False
        )
        assert finished.state == RunState.COMPLETED
        assert finished.succeeded is False

    def test_unknown_success_stays_distinct_from_failure(
        self, index: RunIndex, plan
    ) -> None:
        # A harness crash leaves no verdict. None must not become False,
        # which would report a task failure that was never observed.
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        finished = index.finish(record.run_id, state=RunState.FAILED, now_us=3)
        assert finished.succeeded is None

    def test_an_illegal_transition_is_refused(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        index.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)
        with pytest.raises(InvalidTransitionError):
            index.finish(record.run_id, state=RunState.COMPLETED, now_us=4, succeeded=False)

    def test_finishing_an_unknown_run_raises(self, index: RunIndex) -> None:
        with pytest.raises(KeyError):
            index.finish("nope", state=RunState.COMPLETED, now_us=1)


class TestRecovery:
    def test_a_run_left_running_becomes_abandoned(self, index: RunIndex, plan) -> None:
        """A crash must not strand a run forever.

        `claim_next` skips RUNNING, so a run left there by a killed
        process would never be picked up again and the collection would
        never complete.
        """
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        assert index.abandon_running("exp", now_us=3) == 1
        assert index.get(record.run_id).state == RunState.ABANDONED

    def test_an_abandoned_run_is_claimed_again(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        index.abandon_running("exp", now_us=3)
        resumed = index.claim_next("exp", now_us=4)
        assert resumed.run_id == record.run_id
        assert resumed.attempts == 2

    def test_recovery_does_not_touch_finished_runs(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        index.finish(record.run_id, state=RunState.FAILED, now_us=3)
        assert index.abandon_running("exp", now_us=4) == 0
        assert index.get(record.run_id).state == RunState.FAILED

    def test_the_resume_is_visible_in_the_transition_log(
        self, index: RunIndex, plan
    ) -> None:
        """§80: a resumed run must not look like a clean one.

        Without the log, a run abandoned and resumed twice is
        indistinguishable in `runs` from one that ran straight through.
        """
        index.register_plan(plan, now_us=1)
        record = index.claim_next("exp", now_us=2)
        index.abandon_running("exp", now_us=3)
        index.claim_next("exp", now_us=4)

        states = [t["to_state"] for t in index.transitions(record.run_id)]
        assert states == [
            RunState.PLANNED,
            RunState.RUNNING,
            RunState.ABANDONED,
            RunState.RUNNING,
        ]
        assert any(t["note"] == "resumed" for t in index.transitions(record.run_id))


class TestReading:
    def test_counts_include_states_with_no_runs(self, index: RunIndex, plan) -> None:
        # "No failures" and "failures not counted" must look different.
        index.register_plan(plan, now_us=1)
        counts = index.counts("exp")
        assert set(counts) == RunState.ALL
        assert counts[RunState.FAILED] == 0

    def test_completion_requires_every_run_terminal(
        self, index: RunIndex, plan
    ) -> None:
        index.register_plan(plan, now_us=1)
        assert not index.is_complete("exp")
        while (record := index.claim_next("exp", now_us=2)) is not None:
            index.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)
        assert index.is_complete("exp")

    def test_an_abandoned_run_leaves_the_collection_incomplete(
        self, index: RunIndex, plan
    ) -> None:
        index.register_plan(plan, now_us=1)
        while (record := index.claim_next("exp", now_us=2)) is not None:
            index.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)
        # Force one back to a non-terminal state the way a crash would.
        index._connection.execute(
            "UPDATE runs SET state = ? WHERE run_id = ?",
            (RunState.ABANDONED, plan.runs[0].run_id),
        )
        assert not index.is_complete("exp")

    def test_runs_can_be_filtered_by_state(self, index: RunIndex, plan) -> None:
        index.register_plan(plan, now_us=1)
        index.claim_next("exp", now_us=2)
        assert len(index.runs("exp", state=RunState.RUNNING)) == 1
        assert len(index.runs("exp", state=RunState.PLANNED)) == len(plan) - 1

    def test_the_index_survives_reopening(self, tmp_path: Path, plan) -> None:
        """Resume across processes depends on this.

        An index that only worked while the process lived would be an
        in-memory cursor with extra steps.
        """
        path = tmp_path / "index.db"
        with RunIndex(path) as first:
            first.register_plan(plan, now_us=1)
            record = first.claim_next("exp", now_us=2)
            first.finish(record.run_id, state=RunState.COMPLETED, now_us=3, succeeded=True)

        with RunIndex(path) as second:
            assert second.counts("exp")[RunState.COMPLETED] == 1
            assert second.get(record.run_id).succeeded is True
